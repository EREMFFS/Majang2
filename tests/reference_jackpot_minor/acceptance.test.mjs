import assert from 'node:assert/strict';
import {minorCountToHan,summarizeResolvedAwards,migrateMinorDefinitions,nonWinnerHanPoints,qualifiesNormalWin,MINOR_BUNDLE_ROLE_ID} from './minor_bundle.mjs';
import {selectTileAsset,jackpotPanelItems} from './jackpot_tile_visuals.mjs';

for (const [n,han] of [[0,0],[1,0],[3,0],[4,1],[7,1],[8,2],[11,2],[12,3],[15,3],[16,4],[17,4],[24,4],[100,4]]) assert.equal(minorCountToHan(n),han);
for (const n of [-1,1.2,NaN,Infinity]) assert.throws(()=>minorCountToHan(n),RangeError);
const definitions = Array.from({length:24},(_,i)=>({id:'minor_'+i,class:'minor',value:100,conditionId:'unchanged'}));
definitions.push({id:'fixed_bonus',class:'fixed',value:100},{id:'ordinary',class:'han',value:1});
definitions.push({id:'sp_furikomi',class:'fixed',value:100,displayCategory:'小役'});
const awards = definitions.slice(0,8).map(r=>({roleId:r.id,minorPoints:100,evidence:{tileInstanceIds:['t1']}}));
awards.push({...awards[0]},{roleId:'fixed_bonus',fixedPoints:100},{roleId:'ordinary',han:1});
const summary=summarizeResolvedAwards(awards,definitions);
assert.equal(summary.minorCount,8);assert.equal(summary.minorBundleHan,2);assert.equal(summary.individualMinorPoints,0);
assert.equal(summary.minorAwards.length,8);assert(summary.minorAwards.every(a=>a.minorPoints===0));
assert.equal(summary.scoringAwards.filter(a=>a.roleId===MINOR_BUNDLE_ROLE_ID).length,1);
assert(summary.scoringAwards.some(a=>a.fixedPoints===100));
assert(!summary.scoringAwards.some(a=>a.roleId==='minor_0'));
assert.equal(nonWinnerHanPoints(1+summary.minorBundleHan),400);
assert.equal(nonWinnerHanPoints(1+minorCountToHan(16)),1600);
assert.equal(summarizeResolvedAwards([...awards,summary.bundleAward],definitions).minorCount,8);
assert.equal(summarizeResolvedAwards([...awards,summary.bundleAward],definitions).minorBundleHan,2);
const migrated=migrateMinorDefinitions(definitions);
assert.equal(migrated[0].value,0);assert.equal(migrated[0].conditionId,'unchanged');assert.equal(definitions[0].value,100);
assert.equal(migrated.find(a=>a.id==='fixed_bonus').value,100);
assert.equal(migrated.find(a=>a.id==='sp_furikomi').value,0);
assert.equal(migrated.find(a=>a.id==='sp_furikomi').class,'minor');
const furikomi=summarizeResolvedAwards([{roleId:'sp_furikomi',fixedPoints:100,evidence:{eventIds:['ron1']}}],definitions);
assert.equal(furikomi.minorCount,1);assert.equal(furikomi.minorBundleHan,0);
assert.equal(furikomi.scoringAwards.length,0);assert.equal(furikomi.minorAwards[0].fixedPoints,undefined);
assert.deepEqual(furikomi.minorAwards[0].evidence.eventIds,['ron1']);
assert(qualifiesNormalWin({completeShape:true,legalAcquisition:true,minorBundleHan:1}));
assert(!qualifiesNormalWin({completeShape:false,legalAcquisition:true,minorBundleHan:4}));
assert(!qualifiesNormalWin({completeShape:true,legalAcquisition:false,minorBundleHan:4}));
assert(!qualifiesNormalWin({completeShape:true,legalAcquisition:true,minorBundleHan:0}));
const targets=['m1','m2','m3','m4','m5','m6','m7','m8','m9','p1','p2','p3','p4','p5'];
const before=JSON.stringify(targets);
assert.deepEqual(selectTileAsset({kind:'m1',targets}),{path:'assets/jackpot/tiles/m1.png',gold:true});
assert.deepEqual(selectTileAsset({kind:'s8',targets}),{path:'assets/common/tiles/s8.png',gold:false});
assert.deepEqual(selectTileAsset({kind:'m1',targets,faceUp:false}),{path:'assets/common/tiles/back.png',gold:false});
assert.deepEqual(selectTileAsset({kind:'s8',targets,faceUp:false}),{path:'assets/common/tiles/back.png',gold:false});
assert.equal(selectTileAsset({kind:'m1',targets,size:'hd'}).path,'assets/jackpot/tiles_hd/m1.png');
assert.equal(selectTileAsset({kind:'m1',targets,orientation:'east'}).path,'assets/jackpot/tiles_rotated/m1_east.png');
const panel=jackpotPanelItems(targets,['m1','m1','m2','s8']);
assert.equal(panel.length,14);assert(panel.every(p=>p.gold));assert.equal(panel.filter(p=>p.held).length,2);
assert.equal(JSON.stringify(targets),before);
assert.throws(()=>jackpotPanelItems([...targets.slice(0,13),'m1'],[]));
console.log('PASS: minor thresholds, deduplication, fixed points, yaku eligibility, gold selection and hidden tiles.');
