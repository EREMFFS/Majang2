#!/usr/bin/env python3
"""data/*.json を js/data_bundle.js にまとめる（file:// で開いた時の予備）。
JSONを編集したら、サーバー起動で遊ぶ場合は不要。file:// で遊ぶ場合だけ再実行する。
使い方: python3 tools/build_bundle.py
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = {
    'config': 'data/game_config.json', 'roles': 'data/roles.json', 'characters': 'data/characters.json',
    'stages': 'data/stage_tables.json', 'common': 'data/common_assets.json', 'effects': 'data/effects_manifest.json',
    'cpu': 'data/cpu_profiles.json', 'audio': 'data/audio_events.json', 'gold': 'data/gold_manifest.json',
    'orgs': 'data/organizations.json', 'theme': 'data/theme_patch.json',
}
out = {}
for k, p in FILES.items():
    with open(os.path.join(ROOT, p), encoding='utf-8') as f:
        out[k] = json.load(f)
with open(os.path.join(ROOT, 'js', 'data_bundle.js'), 'w', encoding='utf-8') as f:
    f.write('/* generated by tools/build_bundle.py — do not edit; edit data/*.json */\n')
    f.write('window.MJ2_BUNDLE = ' + json.dumps(out, ensure_ascii=False) + ';\n')
print('wrote js/data_bundle.js')

# ---- cache busting: index.html の js/css に内容のハッシュを付ける（ブラウザが古いファイルを使わないように）
import hashlib, re
h = hashlib.sha1()
for d in ('js', 'css'):
    for fn in sorted(os.listdir(os.path.join(ROOT, d))):
        if fn.endswith(('.js', '.css')):
            with open(os.path.join(ROOT, d, fn), 'rb') as f:
                h.update(re.sub(rb'\?v=\w+', b'', f.read()))
for fn in ('fonts.css',):
    with open(os.path.join(ROOT, fn), 'rb') as f:
        h.update(f.read())
build = h.hexdigest()[:10]
ip = os.path.join(ROOT, 'index.html')
with open(ip, encoding='utf-8') as f:
    html = f.read()
html = re.sub(r'((?:src|href)="(?:js|css)/[\w./-]+\.(?:js|css))(\?v=[\w]+)?"', lambda m: m.group(1) + '?v=' + build + '"', html)
html = re.sub(r"(js/audio_embed\.js)(\?v=[\w]+)?", lambda m: m.group(1) + '?v=' + build, html)
with open(ip, 'w', encoding='utf-8') as f:
    f.write(html)
cp = os.path.join(ROOT, 'css', 'game.css')
with open(cp, encoding='utf-8') as f:
    css = f.read()
css = re.sub(r'@import url\("\.\./fonts\.css(\?v=[\w]+)?"\);', '@import url("../fonts.css?v=' + build + '");', css)
with open(cp, 'w', encoding='utf-8') as f:
    f.write(css)
print('build', build)
