#!/usr/bin/env python3
"""音声ファイルを js/audio_embed/*.js に１ファイルずつ埋め込む（index.html を直接開いた file:// でも Web Audio で鳴らすため）。
file:// ではブラウザが音声ファイルを読めないので、その対策。必要になった音だけ読み込む（起動が重くならない）。
BGM は .ogg（Edge / Chrome / Firefox 用）を入れる。
音を差し替えたら再実行: python3 tools/build_audio_embed.py
"""
import json, os, base64, re, shutil
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cfg = json.load(open(os.path.join(ROOT, 'data', 'audio_events.json'), encoding='utf-8'))
paths = []
for e in cfg.get('events', []):
    if e.get('clip') and e['clip'] not in paths: paths.append(e['clip'])
for b in cfg.get('bgm', []):
    # 容量を抑えるため BGM は .ogg だけ埋め込む（Edge / Chrome / Firefox 用。Mac の Safari は start.command で起動すると .m4a を使う）
    f = next((x for x in b['files'] if x.endswith('.ogg')), b['files'][0])
    if f not in paths: paths.append(f)
for cv in (cfg.get('charVoices') or {}).values():
    for f in cv.values():
        if f not in paths: paths.append(f)
out = os.path.join(ROOT, 'js', 'audio_embed')
shutil.rmtree(out, ignore_errors=True)
os.makedirs(out)
old = os.path.join(ROOT, 'js', 'audio_embed.js')
if os.path.exists(old): os.remove(old)
total = 0
for p in paths:
    fp = os.path.join(ROOT, p)
    if not os.path.exists(fp): continue
    name = re.sub(r'[^A-Za-z0-9_.-]', '_', p) + '.js'
    data = base64.b64encode(open(fp, 'rb').read()).decode()
    with open(os.path.join(out, name), 'w', encoding='utf-8') as f:
        f.write('/* generated by tools/build_audio_embed.py */\n(window.MJ2_AUDIO_EMBED = window.MJ2_AUDIO_EMBED || {})[' + json.dumps(p) + '] = "' + data + '";\n')
    total += os.path.getsize(os.path.join(out, name))
print('wrote js/audio_embed/', len(paths), 'files', round(total / 1e6, 1), 'MB')
